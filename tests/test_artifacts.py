"""Artifact matrix suite: every TOML-selected build artifact is valid.

Format validity is checked by magic bytes and structural markers,
so a broken emitter fails here rather than in the field.
"""

import unittest

from paxsy_testlib import ProjectCase, run_paxsy

U = "use std::inout;\n"


def read_bin(path):
    with open(path, "rb") as f:
        return f.read()


class ArtifactMatrixTests(ProjectCase):
    def setUp(self):
        super().setUp()
        self.proj = self.init_demo()
        (self.proj / "src/main.px").write_text(
            U + "func main(): Void { std::inout::println(\"hi\"); }\n")

    def _build_target(self, target):
        config = self.proj / "demo.toml"
        output = 'output = "build/demo.exe"\n' if target in ("pe", "windows-x86_64") else ""
        config.write_text(config.read_text() +
                          '\n[build]\ntarget = "' + target + '"\n' + output)
        r = run_paxsy("build", cwd=self.proj)
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_target_elf(self):
        self._build_target("elf")
        b = read_bin(self.proj / "build/demo")
        self.assertEqual(b[:4], b"\x7fELF")
        self.assertTrue(b[4] == 2 and b[5] == 1, "ELF64 LE expected")

    def test_target_obj(self):
        self._build_target("obj")
        b = read_bin(self.proj / "build/bin/demo.o")
        self.assertEqual(b[:4], b"\x7fELF")
        self.assertEqual(b[16:18], b"\x01\x00", "ET_REL expected")

    def test_target_a(self):
        self._build_target("a")
        b = read_bin(self.proj / "build/artifacts/demo.a")
        self.assertEqual(b[:8], b"!<arch>\n", "ar archive expected")

    def test_target_pe(self):
        self._build_target("pe")
        b = read_bin(self.proj / "build/demo.exe")
        self.assertEqual(b[:2], b"MZ")
        off = int.from_bytes(b[0x3C:0x40], "little")
        self.assertEqual(b[off:off + 4], b"PE\x00\x00")

    def test_target_llvm(self):
        self._build_target("llvm")
        t = (self.proj / "build/artifacts/demo.ll").read_text()
        self.assertIn("generated by paxsy llic", t)
        self.assertIn("px_res", t)
        self.assertIn("@main()", t)

    def test_target_mlir(self):
        self._build_target("mlir")
        t = (self.proj / "build/artifacts/demo.mlir").read_text()
        self.assertIn("func.func", t)
        self.assertIn("cf.", t)

    def test_target_cuda(self):
        self._build_target("cuda")
        t = (self.proj / "build/artifacts/demo.cu").read_text()
        self.assertIn("paxsy CUDA unit", t)
        self.assertIn("cuda_runtime.h", t)

    def test_emit_pe_keeps_native_output_and_uses_separate_path(self):
        config = self.proj / "demo.toml"
        config.write_text(config.read_text() +
                          '\n[build]\npe_output = "build/extra/demo-win.exe"\n'
                          '\n[artifacts]\npe = true\narchive = true\n')
        result = run_paxsy("build", cwd=self.proj)
        self.assertEqual(result.returncode, 0, result.stderr)
        native = (self.proj / "build/demo").read_bytes()
        pe = (self.proj / "build/extra/demo-win.exe").read_bytes()
        self.assertTrue(native.startswith(b"\x7fELF"))
        self.assertTrue(pe.startswith(b"MZ"))
        self.assertTrue((self.proj / "build/artifacts/demo.a").is_file())

    def test_configured_target_selects_pe_artifact(self):
        config = self.proj / "demo.toml"
        config.write_text(config.read_text() +
                          '\n[build]\ntarget = "pe"\n'
                          'output = "build/demo.exe"\n')
        r = run_paxsy("build", cwd=self.proj)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue((self.proj / "build/demo.exe").is_file())


if __name__ == "__main__":
    unittest.main()
